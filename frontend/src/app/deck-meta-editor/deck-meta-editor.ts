import { Component, input, output } from "@angular/core";
import { DatePipe } from "@angular/common";
import { DeckMeta } from "../../types/Deck";

const TOOL_LABELS = { agent: "Generated by the agent", mcp: "Created through MCP", manual: "Written by hand", upload: "Uploaded" };

/** Deck title, description, language and tags. Author, tool and sources are shown but never edited (#13). */
@Component({
    selector: "app-deck-meta-editor",
    imports: [DatePipe],
    templateUrl: "./deck-meta-editor.html",
})
export class DeckMetaEditor {
    meta = input.required<DeckMeta>();
    changed = output<Partial<DeckMeta>>();

    protected toolLabel() {
        const tool = this.meta().tool;
        return tool ? TOOL_LABELS[tool.kind] + (tool.model ? ` (${tool.model})` : "") : undefined;
    }

    // An emptied field is removed from the deck rather than saved as "".
    setText(field: "title" | "description" | "language", value: string) {
        this.changed.emit({ [field]: value.trim() ? value : undefined });
    }

    setTags(value: string) {
        const tags = [...new Set(value.split(",").map((tag) => tag.trim()).filter(Boolean))];
        this.changed.emit({ tags: tags.length ? tags : undefined });
    }
}
