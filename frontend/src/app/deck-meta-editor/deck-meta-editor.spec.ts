import { ComponentFixture, TestBed } from '@angular/core/testing';

import { DeckMetaEditor } from './deck-meta-editor';
import { DeckMeta } from '../../types/Deck';

describe('DeckMetaEditor', () => {
  let fixture: ComponentFixture<DeckMetaEditor>;
  let changes: Partial<DeckMeta>[];

  async function setup(meta: DeckMeta) {
    fixture = TestBed.createComponent(DeckMetaEditor);
    fixture.componentRef.setInput('meta', meta);
    changes = [];
    fixture.componentInstance.changed.subscribe((c) => changes.push(c));
    await fixture.whenStable();
  }

  const el = () => fixture.nativeElement as HTMLElement;
  const type = (selector: string, value: string, event = 'input') => {
    const input = el().querySelector<HTMLInputElement>(selector)!;
    input.value = value;
    input.dispatchEvent(new Event(event));
  };

  it('shows the editable fields', async () => {
    await setup({ title: 'Signals', language: 'en', tags: ['AM', 'FM'] });

    expect(el().querySelector<HTMLInputElement>('#deck-title')!.value).toBe('Signals');
    expect(el().querySelector<HTMLInputElement>('#deck-tags')!.value).toBe('AM, FM');
  });

  it('emits edits and removes a field that was emptied', async () => {
    await setup({ title: 'Signals' });

    type('#deck-title', 'Signals 2');
    type('#deck-title', '  ');
    type('#deck-description', 'Chapter 4');

    expect(changes).toEqual([{ title: 'Signals 2' }, { title: undefined }, { description: 'Chapter 4' }]);
  });

  it('splits tags on commas, trimming and dropping empties and duplicates', async () => {
    await setup({});

    type('#deck-tags', ' AM, FM,,AM ', 'change');
    type('#deck-tags', ' , ', 'change');

    expect(changes).toEqual([{ tags: ['AM', 'FM'] }, { tags: undefined }]);
  });

  it('shows how the deck was made, but never as a field', async () => {
    await setup({ tool: { kind: 'agent', model: 'haiku', generatedAt: '2026-10-20T10:00:00Z' }, author: { id: 'u1', name: 'Ada' }, sources: [{ name: 'a.pdf' }, { name: 'b.pdf' }] });

    const text = el().querySelector('dl')!.textContent!.replace(/\s+/g, ' ');
    expect(text).toContain('Generated by the agent (haiku), 20 Oct 2026');
    expect(text).toContain('Ada');
    expect(text).toContain('a.pdf, b.pdf');
    expect(el().querySelectorAll('input, textarea')).toHaveLength(4);
  });
});
